export function fixPtBrCopy(value) {
  let text = String(value ?? "");
  for (const [pattern, replacement] of MOJIBAKE_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }
  for (const [plain, accented] of WORD_REPLACEMENTS) {
    text = text.replace(new RegExp(`\\b${escapeRegex(plain)}\\b`, "g"), accented);
  }
  for (const [pattern, replacement] of PHRASE_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }
  return text;
}

export function localizeReportPtBr(value) {
  if (typeof value === "string") return fixPtBrCopy(value);
  if (Array.isArray(value)) return value.map(localizeReportPtBr);
  if (!value || typeof value !== "object") return value;

  const result = {};
  for (const [key, child] of Object.entries(value)) {
    result[key] = localizeReportPtBr(child);
  }
  return result;
}

function escapeRegex(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
